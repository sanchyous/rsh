static CURRENT: AtomicUsize = AtomicUsize::new(0);

pub fn th() -> &'static Theme {
    &THEMES[CURRENT.load(Ordering::Relaxed).min(THEMES.len() - 1)]
}

pub fn set_theme(name: &str) {
    let idx = THEMES
        .iter()
        .position(|t| t.name.eq_ignore_ascii_case(name))
        .or_else(|| THEMES.iter().position(|t| t.name.to_lowercase().starts_with(&name.to_lowercase())))
        .unwrap_or(0);
    CURRENT.store(idx, Ordering::Relaxed);
}

pub fn theme_names() -> Vec<&'static str> {
    THEMES.iter().map(|t| t.name).collect()
}

pub fn blend(a: Color, b: Color, t: f32) -> Color {
    match (a, b) {
        (Color::Rgb(r1, g1, b1), Color::Rgb(r2, g2, b2)) => {
            let m = |x: u8, y: u8| (x as f32 + (y as f32 - x as f32) * t).round() as u8;
            Color::Rgb(m(r1, r2), m(g1, g2), m(b1, b2))
        }
        _ => a,
    }
}

pub fn gradient(t: f32) -> Color {
    let g = &th().grad;
    let t = t.clamp(0.0, 1.0) * (g.len() - 1) as f32;
    let i = (t.floor() as usize).min(g.len() - 2);
    blend(g[i], g[i + 1], t - i as f32)
}
